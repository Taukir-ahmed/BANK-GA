import fs from 'node:fs';
import assert from 'node:assert/strict';
import { families } from './mock-families.mjs';

const news = JSON.parse(fs.readFileSync('docs/pdf-extractions/news-index.json','utf8'));
const manifest = JSON.parse(fs.readFileSync('docs/pdf-extractions/manifest.json','utf8'));
assert.equal(families.length,75);
const bySet = {2:[],3:[],4:[]};
families.forEach((family, index) => {
  assert.equal(family.variants.length,2);
  const group=index%3;
  const destinations=group===0 ? [2,3] : group===1 ? [2,4] : [3,4];
  family.variants.forEach((variant,v)=>bySet[destinations[v]].push({...family,variant,readingTrap:family.readingTraps?.[v]}));
});
for (const [number, entries] of Object.entries(bySet)) {
  assert.equal(entries.length,50);
  let seed=261027+Number(number)*997;
  const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/2**32;};
  function shuffle(a){for(let i=a.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;}
  shuffle(entries);
  const keys=shuffle(Array.from({length:50},(_,i)=>i%5));
  const questions=entries.map((entry,i)=>{
    const {month,item,topic,context,variant,readingTrap}=entry;
    const [angle,q,correct,...distractors]=variant;
    assert.equal(distractors.length,4,`Set ${number} Q${i+1}`);
    const source=news.find(n=>n.month===`${month}-2026` && n.item===item);
    assert.ok(source,`Missing source: ${month} ${item}`);
    const document=manifest.find(m=>m.month.toLowerCase()===`${month} 2026`);
    const options=shuffle([...distractors]);options.splice(keys[i],0,correct);
    return {id:`bank-mains-set${number}-q${i+1}`,type:q.includes('\n')?'statements':'mcq',
      q,options,answer:keys[i],topic,angle,familyId:`${month}-2026-news-${item}`,
      ...(readingTrap ? {readingTrap} : {}),
      note:`Answer: ${correct}.\n\n${readingTrap ? `Reading trap: ${readingTrap}\n\n` : ''}Exam link: ${context}\n\nSource: Smart Points, ${document.month}, PDF page ${source.page}, News ${item}.`,
      source:{document:document.file,month:document.month,page:source.page,newsItem:item}};
  });
  const set={id:`bank-mains-mock-${number}-v1`,isMock:true,title:'Bank Mains Mock',subtitle:`Set ${number}`,
    month:'May–September 2026',timeLimitSeconds:2100,negativeMark:0.25,questions};
  fs.writeFileSync(`src/data/mocks/set${number}.js`,
    '// Generated by scripts/build-mocks-2-4.mjs; authored question families: scripts/mock-families.mjs.\nexport default '+JSON.stringify(set,null,2)+';\n');
  const lines=[`# Bank Mains Mock - Set ${number} source log`,'',
    '50 questions with five choices, 35 minutes and +1/-0.25 marking.',
    'The user explicitly requested repeated topics, reworded questions and recall of surrounding facts. Each of 75 source families contributes two different targets across Sets 2-4, never twice within the same set.',
    'Selected Set 1 topics deliberately return with another target. Question stems and choices are independently authored; contextual explanations link publishers, institutions, benefits, locations and other relevant facts.',
    'Eight questions in this set use a familiar opening followed by a specific supporting detail after the comma. Their review notes explain the switch. Targets, choices, answer keys and question order remain stable.',
    'The supplied PDFs are the factual source; not every news claim has been independently verified. Source month and page are preserved. Use the named edition/date when a fact is time-sensitive.',
    '', '| Q | Month | PDF page | News | Topic | Recall target | Family |','|---|---|---:|---:|---|---|---|',
    ...questions.map((q,i)=>`| ${i+1} | ${q.source.month} | ${q.source.page} | ${q.source.newsItem} | ${q.topic} | ${q.angle} | ${q.familyId} |`)];
  fs.writeFileSync(`docs/mock-set-${number}-source.md`,lines.join('\n')+'\n');
  console.log(`Set ${number}: ${questions.length} questions; ${questions.filter(q=>q.type==='statements').length} statement questions; ${questions.filter(q=>q.readingTrap).length} familiar-opening reading traps.`);
}
